#!/usr/bin/env node

/**
 * generate-registry.js
 *
 * Generates icons/registry.ts from the canonical icon set: a sorted, frozen
 * list of every icon name plus the IconName union derived from it.
 *
 * Read-only over the icon directory — it never edits, renames or deletes an
 * SVG. The only file it writes is the registry, and `--check` writes nothing
 * at all.
 *
 * Usage:
 *   node icons/utils/generate-registry.js            # write icons/registry.ts
 *   node icons/utils/generate-registry.js --check    # CI drift check
 *   node icons/utils/generate-registry.js --source ../flat-icons
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, relative } from 'node:path';
import { parseArgs } from 'node:util';
import fg from 'fast-glob';
import { fromIconsRoot, resolveIconSource } from './lib/icon-source.js';

// ─── CLI ────────────────────────────────────────────────────────────────

const { values: args } = parseArgs({
	options: {
		source: { type: 'string', short: 's' },
		out: { type: 'string', short: 'o', default: 'registry.ts' },
		check: { type: 'boolean', default: false },
		help: { type: 'boolean', short: 'h', default: false },
	},
});

if (args.help) {
	console.log(`
Usage: node icons/utils/generate-registry.js [options]

Generates icons/registry.ts from the canonical icon set.

Options:
  -s, --source <dir>  Icon directory (default: icons/flat-icons, then
                      <repo>/flat-icons)
  -o, --out <file>    Output path, relative to icons/ (default: registry.ts)
      --check         Compare against the committed registry and exit non-zero
                      if they differ. Writes nothing. For CI.
  -h, --help          Show this help
  `);
	process.exit(0);
}

/** Prefer a short relative path, but fall back to absolute when it escapes cwd. */
function displayPath(path) {
	const rel = relative(process.cwd(), path);
	return !rel || rel.startsWith('..') ? path : rel;
}

const KEBAB_CASE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function fail(message, details = []) {
	console.error(`\n  ${message}\n`);
	for (const detail of details) {
		console.error(detail ? `    ${detail}` : '');
	}
	console.error();
	process.exit(1);
}

// ─── Collect ────────────────────────────────────────────────────────────

let sourcePath;

try {
	sourcePath = resolveIconSource(args.source);
} catch (error) {
	fail(error.message);
}

const outPath = fromIconsRoot(args.out);

const files = fg
	.sync('**/*.svg', { cwd: sourcePath, onlyFiles: true })
	.sort();

if (files.length === 0) {
	fail(`No SVG files found in ${sourcePath}`);
}

const invalid = [];
const byName = new Map();

for (const file of files) {
	const name = basename(file, extname(file));

	if (!KEBAB_CASE.test(name)) {
		invalid.push(`${file} → "${name}" is not kebab-case`);
		continue;
	}

	if (!byName.has(name)) byName.set(name, []);
	byName.get(name).push(file);
}

if (invalid.length > 0) {
	fail(
		`${invalid.length} icon filename(s) are not valid kebab-case:`,
		invalid,
	);
}

const collisions = [...byName.entries()].filter(
	([, sources]) => sources.length > 1,
);

if (collisions.length > 0) {
	fail(
		`${collisions.length} icon name(s) are claimed by more than one file:`,
		collisions.map(
			([name, sources]) => `"${name}" ← ${sources.join(', ')}`,
		),
	);
}

// Sorted for deterministic output, so regeneration produces no spurious diff.
const names = [...byName.keys()].sort();

// ─── Emit ───────────────────────────────────────────────────────────────

function renderRegistry(iconNames) {
	const entries = iconNames.map((name) => `  '${name}',`).join('\n');

	return [
		'// GENERATED by icons/utils/generate-registry.js — do not edit by hand.',
		'export const iconNames = [',
		entries,
		'] as const;',
		'',
		'export type IconName = (typeof iconNames)[number];',
		'',
	].join('\n');
}

const generated = renderRegistry(names);
const displayOut = displayPath(outPath);

if (args.check) {
	let committed;

	try {
		committed = readFileSync(outPath, 'utf-8');
	} catch {
		fail(`${displayOut} does not exist.`, [
			`${names.length} icon(s) found in ${sourcePath}.`,
			'Run `npm run icons:registry` to generate it.',
		]);
	}

	if (committed === generated) {
		console.log(
			`  ${displayOut} is up to date (${names.length} icons).`,
		);
		process.exit(0);
	}

	// Name-level diff is more actionable than a line diff of the whole file.
	const committedNames = [...committed.matchAll(/^\s*'([^']+)',$/gm)].map(
		(match) => match[1],
	);
	const committedSet = new Set(committedNames);
	const generatedSet = new Set(names);
	const added = names.filter((name) => !committedSet.has(name));
	const removed = committedNames.filter((name) => !generatedSet.has(name));

	const details = [
		...added.map((name) => `+ ${name}`),
		...removed.map((name) => `- ${name}`),
	];

	if (details.length === 0) {
		details.push(
			'Icon names match; the file differs in formatting or ordering.',
		);
	}

	fail(
		`${displayOut} is out of date with ${sourcePath}:`,
		[
			...details,
			'',
			'Run `npm run icons:registry` and commit the result.',
		],
	);
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, generated);

console.log(`  Wrote ${displayOut} (${names.length} icons).`);

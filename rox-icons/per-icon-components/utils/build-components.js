#!/usr/bin/env node

/**
 * build-components.js
 *
 * Generates one Vue icon component per SVG in raw-svg/, plus a barrel and type
 * declarations, into generated/components/. Output is derived and gitignored;
 * this runs before dev, test and build (see package.json scripts).
 *
 * Each SVG is optimized with SVGO, then compiled to plain data — tag names and
 * attributes — that createIcon() turns into vnodes at render time. Nothing is
 * rendered through innerHTML, so icons work under a Trusted Types CSP.
 *
 * Read-only over raw-svg/.
 *
 * Usage:
 *   node icons/utils/build-components.js
 */

import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import fg from 'fast-glob';
import { optimize } from 'svgo';

const iconsRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = resolve(iconsRoot, 'raw-svg');
const outDir = resolve(iconsRoot, 'generated/components');

// Must start with a letter so the component name is a valid identifier.
const KEBAB_CASE = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

// Root <svg> attributes that describe the file, not the drawing. Sizing and
// classes come from Roxbury's styles; a11y attributes from createIcon().
const DROPPED_ROOT_ATTRS = new Set([
	'xmlns',
	'xmlns:xlink',
	'version',
	'width',
	'height',
	'class',
	'style',
	'id',
	'role',
	'aria-hidden',
	'aria-label',
	'focusable',
]);

/** check-circle → CheckCircleIcon */
export function toComponentName(name) {
	const pascal = name
		.split('-')
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join('');
	return `${pascal}Icon`;
}

function fail(message, details = []) {
	console.error(`\n  ${message}\n`);
	for (const detail of details) console.error(`    ${detail}`);
	console.error();
	process.exit(1);
}

/**
 * Optimize one SVG and return its root attributes and children as data:
 *   { attrs: { viewBox, fill?, ... }, children: [[tag, attrs, children?], ...] }
 */
function compileSvg(source, name) {
	let ast;

	optimize(source, {
		multipass: true,
		floatPrecision: 2,
		plugins: [
			'preset-default',
			'removeDimensions',
			'removeTitle',
			// Icons render inline, so two different icons on one page share a
			// document. Prefix ids (gradients, clip paths, masks) per icon so
			// SVGO's minified ids ("a", "b") can't collide across icons.
			{ name: 'prefixIds', params: { prefix: `cnb-${name}`, delim: '-' } },
			// Runs last in each pass; the final pass leaves the optimized tree.
			{
				name: 'captureAst',
				fn: (root) => {
					ast = root;
					return {};
				},
			},
		],
	});

	const svg = ast.children.find((node) => node.type === 'element' && node.name === 'svg');
	if (!svg) throw new Error('no root <svg> element');
	if (!svg.attributes.viewBox) throw new Error('missing viewBox');

	const attrs = {};
	for (const [key, value] of Object.entries(svg.attributes)) {
		if (!DROPPED_ROOT_ATTRS.has(key)) attrs[key] = value;
	}

	// Default to currentColor so single-color icons follow CSS `color`. A root
	// fill from the source (e.g. fill="none" on stroke icons) is kept, and
	// fills on inner elements (fixed-color icons) always win over this.
	attrs.fill ??= 'currentColor';

	return { attrs, children: svg.children.map(toData).filter(Boolean) };
}

function toData(node) {
	if (node.type === 'text' || node.type === 'cdata') {
		return node.value.trim() ? node.value : null;
	}
	if (node.type !== 'element') return null;

	const children = node.children.map(toData).filter(Boolean);
	return children.length ? [node.name, node.attributes, children] : [node.name, node.attributes];
}

// ─── Collect ────────────────────────────────────────────────────────────

const files = fg.sync('*.svg', { cwd: sourceDir }).sort();

if (files.length === 0) fail(`No SVG files found in ${sourceDir}`);

const icons = [];
const errors = [];
const seen = new Map();

for (const file of files) {
	const name = basename(file, '.svg');

	if (!KEBAB_CASE.test(name)) {
		errors.push(`${file}: "${name}" must be kebab-case and start with a letter`);
		continue;
	}

	const componentName = toComponentName(name);
	if (seen.has(componentName)) {
		errors.push(`${file}: ${componentName} collides with ${seen.get(componentName)}`);
		continue;
	}
	seen.set(componentName, file);

	try {
		const compiled = compileSvg(readFileSync(resolve(sourceDir, file), 'utf-8'), name);
		icons.push({ name, componentName, ...compiled });
	} catch (error) {
		errors.push(`${file}: ${error.message}`);
	}
}

if (errors.length) fail(`${errors.length} icon(s) could not be generated:`, errors);

// ─── Emit ───────────────────────────────────────────────────────────────

const HEADER = '// GENERATED by icons/utils/build-components.js — do not edit by hand.';

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

for (const { name, componentName, attrs, children } of icons) {
	writeFileSync(
		resolve(outDir, `${name}.js`),
		[
			HEADER,
			`// Source: raw-svg/${name}.svg`,
			"import { createIcon } from '../../src/create-icon.js';",
			'',
			`export default createIcon(${JSON.stringify(name)}, ${JSON.stringify(attrs)}, ${JSON.stringify(children)});`,
			'',
		].join('\n'),
	);

	// Self-contained so it stays valid wherever it's copied.
	writeFileSync(
		resolve(outDir, `${name}.d.ts`),
		[
			HEADER,
			"import type { DefineComponent } from 'vue';",
			'',
			`declare const ${componentName}: DefineComponent<{ label?: string }>;`,
			`export default ${componentName};`,
			'',
		].join('\n'),
	);
}

const barrel = icons
	.map(({ name, componentName }) => `export { default as ${componentName} } from './${name}.js';`)
	.join('\n');
writeFileSync(resolve(outDir, 'index.js'), `${HEADER}\n${barrel}\n`);

// Explicit .js extensions: under ESM ("type": "module") TypeScript requires
// them in .d.ts re-exports, and maps each one to the matching .d.ts file.
const barrelTypes = icons
	.map(({ name, componentName }) => `export { default as ${componentName} } from './${name}.js';`)
	.join('\n');
writeFileSync(resolve(outDir, 'index.d.ts'), `${HEADER}\n${barrelTypes}\n`);

console.log(`  Generated ${icons.length} icon components in ${outDir}`);
